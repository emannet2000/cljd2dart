#!/usr/bin/env python3
"""Embed runtime.dart into a ClojureDart string constant.

ClojureDart has no compile-time file includes, so the (small) Dart runtime is
kept as a normal .dart file for editing and testability and then embedded into
a generated .cljd namespace. Run this after changing runtime.dart:

    python3 scripts/embed_runtime.py

The generated file is checked in so that a normal `clojure -M:cljd compile`
does not need Python.
"""
from pathlib import Path

root = Path(__file__).resolve().parent.parent
runtime = (root / "runtime.dart").read_text()
out = root / "src" / "cljd2dart" / "runtime_src.cljd"

escaped = runtime.replace("\\", "\\\\").replace('"', '\\"')
out.write_text(
    "(ns cljd2dart.runtime-src)\n\n"
    ";; Generated by scripts/embed_runtime.py from runtime.dart.\n"
    ";; Do not edit this file directly.\n\n"
    '(def runtime-source\n  "' + escaped + '")\n'
)
print(f"wrote {out} ({len(runtime)} bytes of runtime)")
